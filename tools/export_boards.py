"""Export the paper's best boards to Lean (2026-10-18). Reads the same board files as scripts/golden_ceiling_check.py,
keeps per n the first board (in file order) that is a solution with exactly floor(n/phi) toroidal conflicts, checks it
in Python, and writes QueensLean/Ceilings.lean and CeilingsRouteA.lean: one theorem C_<n> per size via Boards.ceiling_exact.
Usage: export_boards.py OUTDIR (the QueensLean source folder); writes Ceilings.lean and CeilingsRouteA.lean."""
import os, re, sys, math
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "..", "data")
FILES = ("ceiling_small_out.txt", "ceiling_out.txt", "tilt_out.txt", "sym_records_28_30_out.txt", "sym_records_32_33_out.txt",
         "mip_26_board_out.txt", "mip_34_board_out.txt", "mip_31_40_boards_out.txt", "mip_42_46_boards_out.txt",
         "sat_68_233_boards_out.txt", "routeA_49_70_boards_out.txt", "routeA_71_90_boards_out.txt")
def ub(n):                     # floor(n/phi) exactly: largest k with (2k + n)^2 <= 5 n^2
    k = 0
    while (2 * (k + 1) + n) ** 2 <= 5 * n * n: k += 1
    return k
def H(p):
    n = len(p); return sum(k * (k - 1) // 2 for k in list(Counter((i + p[i]) % n for i in range(n)).values()) + list(Counter((i - p[i]) % n for i in range(n)).values()))
def ok(p):
    n = len(p); return sorted(p) == list(range(n)) and len({i + p[i] for i in range(n)}) == n and len({i - p[i] for i in range(n)}) == n
assert all(ub(n) == math.floor(n * (math.sqrt(5) - 1) / 2) for n in range(1, 300))
found = {}
for f in [os.path.join(DATA, x) for x in FILES]:
    for line in open(f):
        m = re.match(r"\s*(?:half )?n = (\d+)\b", line)
        if not m: continue
        n = int(m[1])
        for L in re.findall(r"\[([\d, ]+)\]", line):
            A = [int(x) for x in L.split(",")]
            if n not in found and len(A) == n and ok(A) and H(A) == ub(n): found[n] = A
def small(n):                  # brute force for small n if no board on file
    def rec(r, cols, s, d, cur):
        if r == n:
            if H(cur) == ub(n): return list(cur)
            return None
        for c in range(n):
            if c not in cols and r + c not in s and r - c not in d:
                cur.append(c); res = rec(r + 1, cols | {c}, s | {r + c}, d | {r - c}, cur); cur.pop()
                if res: return res
        return None
    return rec(0, frozenset(), frozenset(), frozenset(), [])
paper = [n for n in range(6, 51) if n not in (10, 13, 18)] + [52, 53, 54, 56, 60, 62, 63, 65, 66, 68, 69, 70, 76, 78, 79, 81, 86, 123, 233]
ROUTE_A = [76, 78, 79, 81, 86]   # written to CeilingsRouteA.lean (found by route A, added after v3)
def write(path, ns, sizes, source):
    out = ["import QueensLean.BoardCheck", "", "/-!", "# Exact ceilings from boards",
           "", f"Generated by `lean/tools/export_boards.py` from {source}. Each `C_n` states `⌊n/φ⌋ = k`, that",
           "some `n`-queens solution has exactly `k` toroidal conflicts, and that none has more (so `C(n) = ⌊n/φ⌋`).", "-/", "",
           f"namespace {ns}", "", "open Queens Ceiling Boards", ""]
    for n in sizes:
        A = found.get(n) or (small(n) if n <= 12 else None)
        if A is None: sys.exit(f"no board for n = {n}")
        assert ok(A) and H(A) == ub(n)
        k = ub(n)
        out += [f"/-- `C({n}) = {k}`. -/",
                f"theorem C_{n} : ⌊({n} : ℝ) / Real.goldenRatio⌋ = {k} ∧",
                f"    (∃ p : Equiv.Perm (Fin {n}), Function.Injective (vs p) ∧ Function.Injective (vd p) ∧ conf p = {k}) ∧",
                f"    ∀ p : Equiv.Perm (Fin {n}), Function.Injective (vs p) → Function.Injective (vd p) → conf p ≤ {k} :=",
                f"  ceiling_exact (L := {A}) (by decide +kernel) (by norm_num) (by norm_num)", ""]
    out += [f"end {ns}", ""]
    open(path, "w").write("\n".join(out))
    print(f"{os.path.basename(path)}: {sizes}")
outdir = sys.argv[1]
write(os.path.join(outdir, "Ceilings.lean"), "Ceilings", [n for n in paper if n not in ROUTE_A], "the paper's board files (`data/`)")
write(os.path.join(outdir, "CeilingsRouteA.lean"), "CeilingsRouteA", ROUTE_A, "the route A boards for 71-90 (`data/routeA_71_90_boards_out.txt`)")

"""Write QueensLean/FloorFamilies.lean: the 28 completed Monsky families of the floor construction, one namespace each,
in the order of families.json, via construct_gen.family and construct_gen.lean_family.
Usage: floor_families_gen.py OUTDIR (the QueensLean source folder)."""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import construct_gen as g
CL = [(12, 2), (12, 10), (12, 3), (12, 9), (12, 4), (24, 6), (24, 18), (24, 8), (24, 20), (12, 0)]
HEAD = """import QueensLean.Construct

/-!
# Floor solutions for all n (completed Monsky placements)

Generated by `lean/tools/floor_families_gen.py`. For each family `n = M u + n0` the completed Monsky board is given as
runs of queens with affine coordinates; `floor_sol u` proves it is a solution with exactly `f(n)` conflicts.
-/

"""
fams = {}
for P, r in CL:
    for s in range(2 if r % 2 else 3):
        f = g.family(P, r, s); fams[f"F{f['M']}_{f['n0']}"] = f
order = [e[0] for e in json.load(open(os.path.join(HERE, "families.json")))]
assert sorted(order) == sorted(fams), "families.json and the construction disagree"
open(os.path.join(sys.argv[1], "FloorFamilies.lean"), "w").write(HEAD + "\n".join(g.lean_family(fams[nm], nm) for nm in order))
print(f"FloorFamilies.lean: {len(order)} families")
